#!/bin/sh
# dash-nodes dashd wrapper: builds /tmp/dash.conf from the mounted template, the network and the
# RPC password secret, then execs dashd. /tmp is container-local, so the password never lands on a
# volume or in an image layer.
#
#   DASH_NETWORK       mainnet | testnet                       (default mainnet)
#   RPC_USER           RPC user name                           (default dashnodes)
#   RPC_PASSWORD_FILE  file holding the RPC password           (default /run/secrets/rpc_password)
#   RPC_ALLOW_CIDR     who may call RPC besides localhost      (default 172.30.86.0/24, the compose net)
#   DASHD_DBCACHE_MB   -dbcache in MiB                         (default 1024)
#   DASHD_EXTRA_ARGS   extra dashd flags, word-split
set -eu
umask 077

NETWORK="${DASH_NETWORK:-mainnet}"
RPC_USER="${RPC_USER:-dashnodes}"
PW_FILE="${RPC_PASSWORD_FILE:-/run/secrets/rpc_password}"
CONF=/tmp/dash.conf

RPC_PASSWORD="$(tr -d '\r\n' < "$PW_FILE")"
case "$RPC_USER$RPC_PASSWORD" in
  '' | *'#'* | *' '* | *'"'* | *"'"* | *\\* | *'$'*)
    echo "dash-nodes-dashd: RPC password missing or contains spaces, quotes, #, \\ or \$" >&2
    exit 1
    ;;
esac

cp /etc/dash-nodes/dash.conf "$CONF"
{
  printf '\n# ---- generated by entrypoint ----\n'
  # rpcport, rpcbind and friends only count inside the network's own section.
  case "$NETWORK" in
    mainnet) echo '[main]'; echo 'rpcport=9998' ;;
    testnet) echo 'testnet=1'; echo '[test]'; echo 'rpcport=19998' ;;
    *) echo "dash-nodes-dashd: DASH_NETWORK must be mainnet or testnet" >&2; exit 1 ;;
  esac
  echo 'rpcbind=0.0.0.0'
  echo "rpcallowip=${RPC_ALLOW_CIDR:-172.30.86.0/24}"
  echo "rpcuser=$RPC_USER"
  echo "rpcpassword=$RPC_PASSWORD"
  echo "dbcache=${DASHD_DBCACHE_MB:-1024}"
} >> "$CONF"

# shellcheck disable=SC2086  # DASHD_EXTRA_ARGS is deliberately word-split
exec dashd -conf="$CONF" ${DASHD_EXTRA_ARGS:-}
